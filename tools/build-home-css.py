#!/usr/bin/env python3
"""Combine the existing home styles without changing their cascade or declarations."""
import hashlib
from pathlib import Path
import posixpath
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCES = [
    'css/bootstrap.min.css',
    'css/animate.min.css',
    'css/style.css',
    'css/menu.css',
    'css/responsive.css',
    'css/fontello/css/all-fontello.min.css',
    'css/icon_restaurant/css/icon_restaurants.min.css',
    'css/new_icons/css/icon_set_all.min.css',
    'css/magnific-popup.css',
    'css/pop_up.css',
    'css/custom.css',
    'rev-slider-files/fonts/pe-icon-7-stroke/css/pe-icon-7-stroke.css',
    'rev-slider-files/fonts/font-awesome/css/font-awesome.css',
    'rev-slider-files/css/settings.css',
]


def rebase(css, source):
    def replace(match):
        value = match.group(2).strip()
        if not value or value.startswith(('/', '#')) or re.match(r'^[a-z][a-z0-9+.-]*:', value, re.I):
            return match.group(0)
        # Keep font cache queries and SVG fragment identifiers verbatim.
        path, *suffix = re.split(r'([?#].*)', value, maxsplit=1)
        absolute = posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
        relative = posixpath.relpath(absolute, 'css')
        return 'url(' + match.group(1) + relative + ''.join(suffix) + match.group(1) + ')'

    css = re.sub(r'@charset\s+["\'][^"\']+["\']\s*;', '', css, flags=re.I)
    return re.sub(r'url\(\s*(["\']?)(.*?)\1\s*\)', replace, css, flags=re.I)


def build():
    parts = ['@charset "UTF-8";\n/* Generated by tools/build-home-css.py. Edit the original styles. */\n']
    for source in SOURCES:
        css = (ROOT/source).read_text(encoding='utf-8-sig')
        if re.search(r'@import\s', css):
            raise ValueError('Resolve CSS imports before bundling: ' + source)
        parts.append('\n/* Source: ' + source + ' */\n' + rebase(css, source) + '\n')
    return ''.join(parts).encode('utf-8')


if __name__ == '__main__':
    data = build()
    name = 'home-' + hashlib.sha256(data).hexdigest()[:12] + '.css'
    (ROOT/'css'/name).write_bytes(data)
    print('css/' + name)
